// If a regression test we generated remains in a package, the package must not
// count as "uses subtests": `go test` does not compile it due to
// `//go:build flakesmith`, so later hunts must not skip themselves.
func TestScanIgnoresFilesExcludedByBuildTags(t *testing.T) {
	dir := t.TempDir()
	write := func(name, body string) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("a_test.go", `package p

import "testing"

func TestPlain(t *testing.T) {}
`)
	write("checkout_flakesmith_test.go", `//go:build flakesmith

// Code generated by flakesmith; DO NOT EDIT.

package p

import "testing"

func TestFlakeRegression_TestPlain(t *testing.T) {
	t.Run("victim/TestPlain", TestPlain)
}
`)

	f, err := facts.Scan(dir)
	if err != nil {
		t.Fatal(err)
	}
	if f.Subtests {
		t.Error("a file excluded by a build tag must not count as 'Subtest'")
	}
	if _, ok := f.Clause["TestFlakeRegression_TestPlain"]; ok {
		t.Error("a test in an excluded file must not enter the clause map")
	}
	if _, ok := f.Clause["TestPlain"]; !ok {
		t.Error("the normal test must be in the clause map")
	}
}

func fixture(t *testing.T, name string) string {
	t.Helper()
	p, err := filepath.Abs(filepath.Join("..", "..", "testdata", "fixtures", name))
	if err != nil {
		t.Fatal(err)
	}
	return p
}

func scan(t *testing.T, name string) facts.PkgFacts {
	t.Helper()
	f, err := facts.Scan(fixture(t, name))
	if err != nil {
		t.Fatal(err)
	}
	return f
}

// The static signature of order dependence: the polluter writes, the victim reads.
func TestScanDetectsSharedGlobal(t *testing.T) {
	f := scan(t, "order-basic")

	if got := f.GlobalsWritten["TestPolluter"]; !contains(got, "seeded") {
		t.Errorf("TestPolluter should write 'seeded', got %v", got)
	}
	if got := f.GlobalsRead["TestVictim"]; !contains(got, "seeded") {
		t.Errorf("TestVictim should read 'seeded', got %v", got)
	}
	// The single most valuable line: the intersection.
	if got := f.SharedGlobals(); !contains(got, "seeded") {
		t.Errorf("SharedGlobals should contain 'seeded', got %v", got)
	}
	if got := f.WriterOf("seeded"); !reflect.DeepEqual(got, []string{"TestPolluter"}) {
		t.Errorf("WriterOf(seeded) = %v", got)
	}
	// An unaffected test must not touch any global.
	if got := f.GlobalsWritten["TestUnaffected"]; len(got) != 0 {
		t.Errorf("TestUnaffected must not write, got %v", got)
	}
}

// Two different package clauses = two different test binaries.
func TestScanDetectsClauseMismatch(t *testing.T) {
	f := scan(t, "clause-mismatch")

	clauses := f.Clauses()
	if len(clauses) != 2 {
		t.Fatalf("expected two clauses, got %v", clauses)
	}
	if f.Clause["TestInnerPolluter"] != "clausemismatch" {
		t.Errorf("TestInnerPolluter clause = %q", f.Clause["TestInnerPolluter"])
	}
	if f.Clause["TestOuterVictim"] != "clausemismatch_test" {
		t.Errorf("TestOuterVictim clause = %q", f.Clause["TestOuterVictim"])
	}
}

