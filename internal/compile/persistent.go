// persistentHeader is shared by every class: the file is committed to the
// repository, so it has to be self-describing and inert without the build tag.
//
// It repeats the witness steps literally rather than calling into flakesmith:
// a regression test that needs the tool installed to compile would be useless
// in a fork, a vendor directory or an air-gapped CI.
const persistentHeader = `//go:build {{.Tag}}

// Code generated by flakesmith; DO NOT EDIT.
//
// Capsule: {{.CapsuleID}}
// Class: {{.Kind}}{{if .Polluters}} · Polluter: {{.Polluters}}{{end}}
// Victim: {{.Victim}}
//
// This test records that {{.Victim}} is a flake of class {{.Kind}}.
// It carries the "{{.Tag}}" build tag so it does not affect the default suite.
//
// Reproduce:
//   {{.Command}}
//
// To run it on every run, delete this line: //go:build {{.Tag}}

package {{.Clause}}
`

// The body depends on the class, because reproducing the flake depends on it:
// an order witness is a t.Run chain, a parallel one needs t.Parallel() and
// enough -parallel slots, a repeat one needs the same test several times in one
// process, and an env one needs the variable the capsule never stores.
//
// A single serial body for all four was the bug: three classes went green, so
// `compile` printed "the test will be RED now" and was wrong.
const orderBody = `
import "testing"

// {{.Func}} is the witness's permanent record: red before the fix,
// green after it, guarding the regression permanently.
func {{.Func}}(t *testing.T) {
{{- range .Steps}}
	t.Run({{quote .Label}}, {{.Func}})
{{- end}}
}
`

const parallelBody = `
import "testing"

// {{.Func}} is the witness's permanent record: steps overlap in the parallel pool.
// Run alone it gives a false green; at least {{.Parallel}} slots are needed.
func {{.Func}}(t *testing.T) {
{{- range .Steps}}
	t.Run({{quote .Label}}, func(t *testing.T) {
{{- if .WrapParallel}}
		t.Parallel()
{{- end}}
		{{.Func}}(t)
	})
{{- end}}
}
`

const repeatBody = `
import (
	"strconv"
	"testing"
)

// {{.Func}} is the witness's permanent record: runs the same test {{.Count}} times
// in one process. Same semantics as -count={{.Count}}, in a single go test call.
func {{.Func}}(t *testing.T) {
	for i := 0; i < {{.Count}}; i++ {
		t.Run(strconv.Itoa(i+1), {{.Victim}})
	}
}
`

const envBody = `
import (
	"os"
	"testing"
)

// {{.Func}} is the witness's permanent record: the result depends on the env value.
// The value is not stored in the capsule (it may be secret); if the variable is
// missing the test SKIPs, so it never looks "green" with false confidence.
func {{.Func}}(t *testing.T) {
{{- range .EnvKeys}}
	if _, ok := os.LookupEnv({{quote .}}); !ok {
		t.Skip("flakesmith: this regression does not run without the env variable set: " + {{quote .}})
	}
{{- end}}
	t.Run({{quote .VictimLabel}}, {{.Victim}})
}
`

type templateData struct {
	Tag         string
	CapsuleID   string
	Kind        string
	Polluters   string
	Victim      string
	VictimLabel string
	RelDir      string
	Func        string
	Clause      string
	Command     string
	Steps       []domain.Step
	Count       int
	Parallel    int
	EnvKeys     []string
}

// Options decide where and how the regression test is written.
type Options struct {
	// Dir is the package directory to write into.
	Dir string
	// SourceFile names the file the victim lives in, if known. It only
	// influences the output filename.
	SourceFile string
	// Write enables touching the filesystem. False -> Render only.
	Write bool
}

// Render returns the gofmt-clean source of the permanent regression test.
func Render(c domain.Capsule, clause string) ([]byte, error) {
	if clause == "" {
		return nil, fmt.Errorf("%w: unknown package clause", domain.ErrInternal)
	}
	body, err := bodyFor(c.Kind)
	if err != nil {
		return nil, err
	}

	steps := c.Witness.Steps
	if len(steps) == 0 {
		steps = []domain.Step{{Label: domain.VictimLabel(c.Witness.Victim.Name), Test: c.Witness.Victim}}
	}

	relDir := c.Target.RelDir
	if relDir == "" {
		relDir = "."
	}

	data := templateData{
		Tag:         domain.PersistentBuildTag,
		CapsuleID:   c.ID,
		Kind:        string(c.Kind),
		Polluters:   polluterNames(c.Witness.Polluters),
		Victim:      c.Witness.Victim.Name,
		VictimLabel: domain.VictimLabel(c.Witness.Victim.Name),
		RelDir:      relDir,
		Func:        domain.PersistentFuncName(c.Witness.Victim.Name),
		Clause:      clause,
		Command:     CommandLine(c),
		Steps:       steps,
		Count:       repeatCount(c),
		Parallel:    parallelWidth(c, steps),
		EnvKeys:     c.Witness.EnvDiff,
	}

	var buf bytes.Buffer
	for _, tmplText := range []string{persistentHeader, body} {
		tmpl, err := template.New("persistent").Funcs(template.FuncMap{
			"quote": strconv.Quote,
		}).Parse(tmplText)
		if err != nil {
			return nil, fmt.Errorf("%w: template: %v", domain.ErrInternal, err)
		}
		if err := tmpl.Execute(&buf, data); err != nil {
			return nil, fmt.Errorf("%w: template: %v", domain.ErrInternal, err)
		}
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		// A regression test we cannot compile is worse than none: it would
		// break the user's build with our bug.
		return nil, fmt.Errorf("%w: generated test has invalid syntax: %v", domain.ErrInternal, err)
	}
	return src, nil
}

// bodyFor picks the template that can actually reproduce this class.
func bodyFor(kind domain.Kind) (string, error) {
	switch kind {
	case domain.KindOrder:
		return orderBody, nil
	case domain.KindParallel:
		return parallelBody, nil
	case domain.KindRepeat:
		return repeatBody, nil
	case domain.KindEnv:
		return envBody, nil
	default:
		return "", fmt.Errorf("%w: unknown flake class %q", domain.ErrInternal, kind)
	}
}

// Write renders and writes the regression test, refusing to overwrite a file
// this tool did not generate.
func Write(c domain.Capsule, clause string, opt Options) (string, error) {
	src, err := Render(c, clause)
	if err != nil {
		return "", err
	}
	if !opt.Write {
		return "", nil
	}

	name := OutputName(opt.Dir, opt.SourceFile, c.Witness.Victim.Name)
	path := filepath.Join(opt.Dir, name)

	if existing, err := os.ReadFile(path); err == nil {
		if !isGenerated(existing) {
			return "", fmt.Errorf("%w: %s was not generated by flakesmith, refusing to overwrite",
				domain.ErrUsage, name)
		}
		// Same content: leave the file alone so `git status` stays clean and
		// a re-run does not produce a spurious diff.
		if bytes.Equal(existing, src) {
			return path, nil
		}
	}

	if err := os.WriteFile(path, src, 0o644); err != nil {
		return "", fmt.Errorf("%w: cannot write %s: %v", domain.ErrInternal, name, err)
	}
	return path, nil
}

// isGenerated is the ownership check: only overwrite files that carry our
// header. A user's hand-written checkout_flakesmith_test.go is theirs.
func isGenerated(src []byte) bool {
	head := string(src)
	if len(head) > 4096 {
		head = head[:4096]
	}
	return strings.Contains(head, "Code generated by flakesmith")
}

func polluterNames(ids []domain.TestID) string {
	names := make([]string, len(ids))
	for i, id := range ids {
		names[i] = id.Name
	}
	return strings.Join(names, ", ")
}

// repeatCount is how many in-process repetitions the witness needs.
func repeatCount(c domain.Capsule) int {
	if c.Witness.Flags.Count > 0 {
		return c.Witness.Flags.Count
	}
	return 10
}

// parallelWidth is how many -parallel slots the witness needs: one per step,
// because a smaller width makes Go serialise the subtests and the witness
// silently proves nothing.
func parallelWidth(c domain.Capsule, steps []domain.Step) int {
	if c.Witness.Flags.Parallel > 0 {
		return c.Witness.Flags.Parallel
	}
	if len(steps) > 0 {
		return len(steps)
	}
	return 1
}

// CommandLine is the exact `go test` invocation that runs the regression test.
//
// Every branch is derived from the class and the witness, never hardcoded: a
// parallel witness replayed with -parallel=1 executes its subtests one after
// another and reports "passed" — the worst possible artifact, a command that
// looks right and lies.
func CommandLine(c domain.Capsule) string {
	relDir := c.Target.RelDir
	if relDir == "" {
		relDir = "."
	}

	// For an env flake the value is never written to the capsule; the user puts
	// their own value in. Leaving it empty would make the command unrunnable.
	var prefix strings.Builder
	for _, key := range c.Witness.EnvDiff {
		fmt.Fprintf(&prefix, "%s=%s ", key, policy.RedactionPlaceholder)
	}

	fn := domain.PersistentFuncName(c.Witness.Victim.Name)
	// -race is part of the witness: if it drops from the command on race-only
	// flakes, the generated test stays green and the artifact lies about "not reproducing".
	race := ""
	if c.Witness.Flags.Race {
		race = "-race "
	}
	base := fmt.Sprintf("go test %s%s -tags %s -run '^%s$'", race, relDir, domain.PersistentBuildTag, fn)

	switch c.Kind {
	case domain.KindRepeat:
		return fmt.Sprintf("%s%s -count=%d", prefix.String(), base, repeatCount(c))
	case domain.KindEnv:
		// The victim itself, not a narrowed witness: the difference is only in the env.
		return fmt.Sprintf("%s%s -count=1", prefix.String(), base)
	case domain.KindParallel:
		return fmt.Sprintf("%s%s -count=1 -parallel=%d", prefix.String(), base, parallelWidth(c, c.Witness.Steps))
	default:
		return fmt.Sprintf("%s%s -count=1 -parallel=1", prefix.String(), base)
	}
}

// VerifySpec is the run that proves the generated test is red before the fix.
//
// It is the only honest defense against "compile prints RED and the test
// passes": the artifact is executed once, exactly as the user would run it.
func VerifySpec(c domain.Capsule, dir string) domain.RunSpec {
	spec := domain.RunSpec{
		Package:  dir,
		RunRegex: "^" + domain.PersistentFuncName(c.Witness.Victim.Name) + "$",
		Count:    1,
		Tags:     []string{domain.PersistentBuildTag},
		Parallel: 1,
		// If the witness was found with -race, verification must run -race too:
		// otherwise on a race-only flake the artifact stays green and --verify
		// wrongly says "not reproducing".
		Race: c.Witness.Flags.Race,
	}
	if c.Kind == domain.KindParallel {
		spec.Parallel = parallelWidth(c, c.Witness.Steps)
	}
	return spec
}

// OutputName retains an existing legacy file for its own victim only. New
// victims get separate paths; recompiling either victim never removes another.
func OutputName(dir, source, victim string) string {
	legacy := domain.PersistentFileName(source)
	if src, err := os.ReadFile(filepath.Join(dir, legacy)); err == nil && isGenerated(src) {
		if file, err := parser.ParseFile(token.NewFileSet(), legacy, src, 0); err == nil {
			for _, decl := range file.Decls {
				if fn, ok := decl.(*ast.FuncDecl); ok && fn.Name.Name == domain.PersistentFuncName(victim) {
					return legacy
				}
			}
		}
	}
	return domain.PersistentFileName(source, victim)
}
